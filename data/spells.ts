export function levelLabel(level: number, long = false) {
  if (level === 0) return 'Cantrip'
  const suffix = ['th', 'st', 'nd', 'rd'][level] ?? 'th'
  return long ? `${level}${suffix}-level` : `${level}${suffix}`
}

