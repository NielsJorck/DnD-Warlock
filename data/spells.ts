// Lucan's spell glossary. Rules text is paraphrased from the 2014 sources;
// "atPact" describes the effect when cast from a 5th-level pact slot.

export type SpellStatus = 'known' | 'book' | 'wishlist' | 'candidate' | 'future'
export type SpellAccess = 'Warlock' | 'Pact of the Tome' | 'Telekinetic' | 'Genie Patron' | 'Dao Patron' | 'Book of Shadows'
export type School =
  | 'Abjuration'
  | 'Conjuration'
  | 'Divination'
  | 'Enchantment'
  | 'Evocation'
  | 'Illusion'
  | 'Necromancy'
  | 'Transmutation'

export interface Spell {
  slug: string
  name: string
  level: number
  school: School
  castingTime: string
  range: string
  components: string
  material?: string
  duration: string
  concentration: boolean
  ritual: boolean
  source: string
  access: SpellAccess
  status: SpellStatus
  priority?: 'High' | 'Useful' | 'Additional'
  role: string
  summary: string
  atPact?: string
  notes?: string
  damage?: string
  save?: string
  attack?: boolean
}

