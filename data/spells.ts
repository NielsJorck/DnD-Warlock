// Lucan's spell glossary. Rules text is paraphrased from the 2014 sources;
// "atPact" describes the effect when cast from a 5th-level pact slot.

export type SpellStatus = 'known' | 'book' | 'candidate' | 'future'
export type SpellAccess = 'Warlock' | 'Pact of the Tome' | 'Genie Patron' | 'Dao Patron' | 'Book of Shadows'
export type School =
  | 'Abjuration'
  | 'Conjuration'
  | 'Divination'
  | 'Enchantment'
  | 'Evocation'
  | 'Illusion'
  | 'Necromancy'
  | 'Transmutation'

export interface Spell {
  slug: string
  name: string
  level: number
  school: School
  castingTime: string
  range: string
  components: string
  material?: string
  duration: string
  concentration: boolean
  ritual: boolean
  source: string
  access: SpellAccess
  status: SpellStatus
  role: string
  summary: string
  atPact?: string
  notes?: string
  damage?: string
  save?: string
  attack?: boolean
}

export const statusLabels: Record<SpellStatus, string> = {
  known: 'Known',
  book: 'Book of Shadows',
  candidate: 'Candidate',
  future: 'Future'
}

export const schoolGlyph: Record<School, string> = {
  Abjuration: '⛨',
  Conjuration: '✧',
  Divination: '◉',
  Enchantment: '♥',
  Evocation: '✶',
  Illusion: '◐',
  Necromancy: '☠',
  Transmutation: '⟲'
}

export function levelLabel(level: number, long = false) {
  if (level === 0) return 'Cantrip'
  const suffix = ['th', 'st', 'nd', 'rd'][level] ?? 'th'
  return long ? `${level}${suffix}-level` : `${level}${suffix}`
}

